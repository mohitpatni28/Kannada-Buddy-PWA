import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";

const root = process.cwd();
const publicDir = path.join(root, "public");
const nextStaticDir = path.join(root, ".next", "static");
const outputPath = path.join(publicDir, "sw.js");
const routes = ["/", "/today", "/travel", "/phrasebook", "/review", "/settings", "/library", "/admin", "/sources"];

async function filesBelow(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const absolute = path.join(directory, entry.name);
    return entry.isDirectory() ? filesBelow(absolute) : [absolute];
  }));
  return nested.flat();
}

const publicAbsoluteFiles = (await filesBelow(publicDir))
  .filter((file) => file !== outputPath && !file.endsWith(".DS_Store"));
const publicFiles = publicAbsoluteFiles
  .map((file) => `/${path.relative(publicDir, file).split(path.sep).join("/")}`);
const nextFiles = (await filesBelow(nextStaticDir))
  .filter((file) => !file.endsWith(".map") && !file.endsWith(".DS_Store"))
  .map((file) => `/_next/static/${path.relative(nextStaticDir, file).split(path.sep).join("/")}`);
const precache = [...new Set([...routes, ...publicFiles, ...nextFiles])].sort();
const revisionHash = createHash("sha256").update(precache.join("\n"));
for (const file of publicAbsoluteFiles) revisionHash.update(await fs.readFile(file));
const revision = revisionHash.digest("hex").slice(0, 12);

const source = `/* Generated by scripts/generate-service-worker.mjs after next build. */
const CACHE_PREFIX = "kannada-buddy-";
const CACHE_NAME = CACHE_PREFIX + "${revision}";
const PRECACHE_URLS = ${JSON.stringify(precache, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then((cache) => cache.addAll(PRECACHE_URLS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

async function cacheResponse(request, response) {
  if (response.ok && response.type !== "opaque") {
    const cache = await caches.open(CACHE_NAME);
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  const isStaticAsset = url.pathname.startsWith("/_next/static/") || PRECACHE_URLS.includes(url.pathname);
  const isRscRequest = request.headers.get("RSC") === "1" || request.headers.has("Next-Router-State-Tree");

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request)
        .then((response) => cacheResponse(request, response))
        .catch(async () => (await caches.match(request, { ignoreSearch: true })) || (await caches.match("/")))
    );
    return;
  }

  if (isStaticAsset) {
    event.respondWith(
      caches.match(request, { ignoreSearch: true }).then((cached) => cached || fetch(request).then((response) => cacheResponse(request, response)))
    );
    return;
  }

  if (isRscRequest) {
    event.respondWith(
      fetch(request)
        .then((response) => cacheResponse(request, response))
        .catch(() => new Response("Offline navigation requires a cached full-page request.", { status: 503, headers: { "Content-Type": "text/plain" } }))
    );
    return;
  }

  event.respondWith(
    fetch(request)
      .then((response) => cacheResponse(request, response))
      .catch(async () => (await caches.match(request, { ignoreSearch: true })) || new Response("Offline resource unavailable.", { status: 503 }))
  );
});
`;

await fs.writeFile(outputPath, source);
console.log(`Generated public/sw.js with ${precache.length} precached URLs (${revision}).`);
